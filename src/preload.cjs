const { contextBridge, ipcRenderer, webUtils } = require("electron");

const invoke = (channel) => (arg) => ipcRenderer.invoke(channel, arg);

contextBridge.exposeInMainWorld("api", {
  platform: process.platform,
  getState: invoke("state:get"),
  setSettings: invoke("settings:set"),
  grepFiles: invoke("fs:grep"),
  checkClaude: invoke("claude:check"),
  setClaudeToken: invoke("claude-token:set"),
  clearClaudeToken: invoke("claude-token:clear"),
  pmGet: invoke("pm:get"),
  pmRefresh: invoke("pm:refresh"),
  pmSetToken: invoke("pm:set-token"),
  pmLogin: invoke("pm:login"),
  addProject: invoke("project:add"),
  renameProject: invoke("project:rename"),
  moveProject: invoke("project:move"),
  pinProject: invoke("project:pin"),
  createGroup: invoke("group:create"),
  updateGroup: invoke("group:update"),
  deleteGroup: invoke("group:delete"),
  removeProject: invoke("project:remove"),
  openProject: invoke("project:open"),
  getAuth: invoke("auth:get"),
  refreshAuth: invoke("auth:refresh"),
  login: invoke("auth:login"),
  sendAuthCode: invoke("auth:code"),
  cancelLogin: invoke("auth:cancel"),
  logout: invoke("auth:logout"),
  termCreate: invoke("term:create"),
  termKill: invoke("term:kill"),
  termWrite: (id, data) => ipcRenderer.send("term:write", { id, data }),
  termResize: (id, cols, rows) => ipcRenderer.send("term:resize", { id, cols, rows }),
  readFile: invoke("fs:read"),
  searchFiles: invoke("fs:search"),
  pickAttachments: invoke("attach:pick"),
  attachPaths: invoke("attach:paths"),
  attachImageData: invoke("attach:image-data"),
  // File kéo thả vào app -> đường dẫn thật trên máy.
  pathForFile: (file) => webUtils.getPathForFile(file),
  createPath: invoke("fs:create"),
  renamePath: invoke("fs:rename"),
  trashPath: invoke("fs:trash"),
  writeFile: invoke("fs:write"),
  gitStatus: invoke("git:status"),
  gitFiles: invoke("git:files"),
  openUrl: invoke("open:url"),
  listDir: invoke("fs:list"),
  openFile: invoke("fs:open"),
  getLog: invoke("task:log"),
  claudeMeta: invoke("claude:meta"),
  createTask: invoke("task:create"),
  renameTask: invoke("task:rename"),
  sendToTask: invoke("task:send"),
  stopTask: invoke("task:stop"),
  deleteTask: invoke("task:delete"),
  setTaskMode: invoke("task:set-mode"),
  taskContext: invoke("task:context"),
  respondPermission: invoke("permission:respond"),
  answerQuestion: invoke("question:answer"),
  on: (channel, fn) => {
    const allowed = ["menu:save", "menu:close-tab", "menu:search", "menu:toggle-terminal", "term:data", "term:exit", "auth:update", "task:update", "task:entry", "task:finished", "task:needs-approval", "pm:update"];
    if (!allowed.includes(channel)) return;
    ipcRenderer.on(channel, (_e, payload) => fn(payload));
  },
});
